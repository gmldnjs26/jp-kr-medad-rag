# ### 2. 日本の規制（医療法・医療広告ガイドライン）における違反理由

# 日本の医療法および「医療広告ガイドライン」において、以下の禁止事項に抵触します。

# 1. **虚偽広告の禁止（医療法第6-5条第1項）**
#    * **「絶対に腫れない」「絶対安全」**：医療行為に「絶対（確実）」は存在しません。内出血や感染症、腫れのリスクはゼロにできないため、事実に反する「虚偽広告」とみなされます（虚偽広告は罰則が最も重く、6か月以下の懲役または30万円以下の罰金の対象）。
# 2. **誇大広告の禁止（医療法第6-5条第2項第2号）**
#    * **「痛みゼロ」「ダウンタイムはありません」**：麻酔時や施術後の鈍痛、一定の組織の回復期間（ダウンタイム）は必ず生じます。事実を著しく誇張し、消費者を誤認させる「誇大広告」に該当します。
# 3. **効果や安全性を保証する表現の禁止**
#    * ガイドライン上、「絶対」「100%」「確実」など、治療効果や安全性を保証する文言の使用は厳格に禁止されています。

