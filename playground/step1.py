# 1. **治療効果の保証・消費者を欺瞞する広告の禁止（医療法第56条第2項第2号・第3号）**
#    * 韓国医療法では、治療効果を保証して患者を誘引する広告や、医療人の技術・施術方法に関して嘘をつき、または誇張する広告を禁止しています。
